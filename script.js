        function generateMealPrep() {
            const days = parseInt(document.getElementById('prepDays').value);
            const mealsPerDay = parseInt(document.getElementById('mealsPerDay').value);
            const selectedRecipes = Array.from(document.querySelectorAll('.recipe-checkbox:checked'))
                .map(cb => savedRecipes[parseInt(cb.value)]);

            if (selectedRecipes.length === 0) {
                showToast('Please select at least one recipe', 'error');
                return;
            }

            // Generate meal plan
            const mealPlan = [];
            for (let day = 0; day < days; day++) {
                const dayMeals = [];
                for (let meal = 0; meal < mealsPerDay; meal++) {
                    const recipe = selectedRecipes[Math.floor(Math.random() * selectedRecipes.length)];
                    dayMeals.push(recipe);
                }
                mealPlan.push(dayMeals);
            }

            // Generate shopping list
            const shoppingList = {};
            selectedRecipes.forEach(recipe => {
                recipe.ingredients.forEach(ingredient => {
                    if (shoppingList[ingredient.name]) {
                        shoppingList[ingredient.name] += ingredient.amount;
                    } else {
                        shoppingList[ingredient.name] = ingredient.amount;
                    }
                });
            });

            // Display calendar
            const calendarGrid = document.getElementById('calendarGrid');
            const dayNames = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];
            calendarGrid.innerHTML = mealPlan.map((day, index) => `
                <div class="dark-card rounded-xl p-4">
                    <h4 class="font-semibold text-purple-400 mb-3">${dayNames[index]}</h4>
                    <div class="space-y-2">
                        ${day.map((meal, mealIndex) => `
                            <div class="text-sm">
                                <span class="font-medium">Meal ${mealIndex + 1}:</span> ${meal.name}
                            </div>
                        `).join('')}
                    </div>
                </div>
            `).join('');

            // Display shopping list
            const shoppingListContainer = document.getElementById('shoppingList');
            shoppingListContainer.innerHTML = Object.entries(shoppingList).map(([item, amount]) => `
                <div class="flex justify-between items-center p-2 bg-gray-800 rounded-lg">
                    <span class="text-sm">${item}</span>
                    <span class="text-sm font-medium">${amount}</span>
                </div>
            `).join('');

            document.getElementById('mealPrepCalendar').classList.remove('hidden');
            showToast('Meal prep plan generated successfully!');
        }

