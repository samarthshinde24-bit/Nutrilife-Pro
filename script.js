        function filterByNutrient() {
            const nutrientFocus = document.getElementById('nutrientFocus').value;
            let results = comprehensiveFoodDatabase;

            if (nutrientFocus === 'protein') {
                results = results.filter(food => food.protein > 10);
            } else if (nutrientFocus === 'vitaminC') {
                results = results.filter(food => food.vitamins.vitaminC && parseFloat(food.vitamins.vitaminC) > 20);
            } else if (nutrientFocus === 'iron') {
                results = results.filter(food => food.minerals.iron && parseFloat(food.minerals.iron) > 2);
            } else if (nutrientFocus === 'calcium') {
                results = results.filter(food => food.minerals.calcium && parseFloat(food.minerals.calcium) > 100);
            } else if (nutrientFocus === 'fiber') {
                results = results.filter(food => food.fiber > 5);
            }

            displayFoodResults(results);
        }

