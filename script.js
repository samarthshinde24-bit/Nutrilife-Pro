        function searchFoodDatabase(query) {
            const category = document.getElementById('foodCategory').value;
            const sortBy = document.getElementById('sortBy').value;

            let results = comprehensiveFoodDatabase;

            // Filter by search term
            if (query) {
                results = results.filter(food =>
                    food.name.toLowerCase().includes(query.toLowerCase())
                );
            }

            // Filter by category
            if (category !== 'all') {
                results = results.filter(food => food.category === category);
            }

            // Sort results
            results.sort((a, b) => {
                if (sortBy === 'name') {
                    return a.name.localeCompare(b.name);
                } else if (sortBy === 'calories') {
                    return a.calories - b.calories;
                } else if (sortBy === 'protein') {
                    return a.protein - b.protein;
                } else if (sortBy === 'vitamins') {
                    const aVitamins = Object.keys(a.vitamins).length;
                    const bVitamins = Object.keys(b.vitamins).length;
                    return bVitamins - aVitamins;
                }
            });

            displayFoodResults(results);
        }

