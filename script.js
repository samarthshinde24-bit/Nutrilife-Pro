        // BMR Calculator Functions
        function calculateBMR() {
            const age = parseInt(document.getElementById('age').value);
            const gender = document.getElementById('gender').value;
            const height = parseFloat(document.getElementById('height').value);
            const weight = parseFloat(document.getElementById('weight').value);
            const activity = document.getElementById('activity').value;

            if (!age || !height || !weight) {
                showToast('Please fill in all fields', 'error');
                return;
            }

            // Calculate BMR using Mifflin-St Jeor Equation
            let bmr;
            if (gender === 'male') {
                bmr = 10 * weight + 6.25 * height - 5 * age + 5;
            } else {
                bmr = 10 * weight + 6.25 * height - 5 * age - 161;
            }

            // Activity multipliers
            const activityMultipliers = {
                sedentary: 1.2,
                light: 1.375,
                moderate: 1.55,
                active: 1.725,
                very: 1.9
            };

            const tdee = bmr * activityMultipliers[activity];

            // Display results
            document.getElementById('bmrValue').textContent = Math.round(bmr);
            document.getElementById('tdeeValue').textContent = Math.round(tdee);
            document.getElementById('loseWeight').textContent = Math.round(tdee - 500) + ' cal';
            document.getElementById('maintainWeight').textContent = Math.round(tdee) + ' cal';
            document.getElementById('gainWeight').textContent = Math.round(tdee + 500) + ' cal';

            showToast('BMR calculated successfully!');
        }

        // BMI Calculator Functions
        function calculateBMI() {
            const height = parseFloat(document.getElementById('bmiHeight').value) / 100; // Convert to meters
            const weight = parseFloat(document.getElementById('bmiWeight').value);

            if (!height || !weight) {
                showToast('Please fill in all fields', 'error');
                return;
            }

            const bmi = weight / (height * height);
            let category;
            let advice;

            if (bmi < 18.5) {
                category = 'Underweight';
                advice = 'Consider consulting with a healthcare provider about healthy weight gain strategies.';
            } else if (bmi < 25) {
                category = 'Normal weight';
                advice = 'Great job! Maintain your current healthy lifestyle.';
            } else if (bmi < 30) {
                category = 'Overweight';
                advice = 'Consider incorporating more physical activity and balanced nutrition into your routine.';
            } else {
                category = 'Obesity';
                advice = 'It\'s recommended to consult with a healthcare provider for personalized advice.';
            }

            document.getElementById('bmiValue').textContent = bmi.toFixed(1);
            document.getElementById('bmiCategory').textContent = category;
            document.querySelector('#bmiAdvice p').textContent = advice;

            showToast('BMI calculated successfully!');
        }

